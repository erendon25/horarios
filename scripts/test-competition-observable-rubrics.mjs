 const people=[];
 for(let i=0;i<3;i++)people.push(await scalar("insert into staff_profiles(store_id,first_name,position) values($1,$2,$3) returning id",[store,`Perfil ${i}`,i===0?'ENTRENADOR':'COLABORADOR']));
 await db.query("insert into user_profiles(id,store_id,role,staff_profile_id) values($1,$3,'admin',null),($2,$3,'collaborator',$4)",[admin,collaborator,store,people[1]]);
 await login(admin);
 const setup=async name=>{
  const c=await cmd(null,'create',{store_id:store,name});
  const team=await cmd(c.id,'team',{name:'Equipo',trainer_staff_id:people[0]});
  const areas=await rows('select * from competition_areas where competition_id=$1 order by sort_order',[c.id]);
  for(const area of areas)await cmd(c.id,'area',{...area,maximum_duration_ms:45000});
  const area=areas.find(a=>a.name==='Sheetout');
  let entry;
  for(const person of people.slice(1)){
   const member=await cmd(c.id,'member',{team_id:team.id,staff_id:person});
   const e=await cmd(c.id,'entry',{member_id:member.id,area_id:area.id});
   if(!entry)entry=e;
  }
  return {c,area,entry,areas};
 };
