 await db.exec('reset role');
 await db.exec(await readFile('supabase/migrations/20260930231033_competition_observable_rubrics.sql','utf8'));
 await login(admin);
 assert.equal((await rows('select * from competition_evaluation_scores where evaluation_id=$1',[old.id])).every(s=>s.checklist.length===0),true);
 await cmd(legacy.c.id,'finalize',{evaluation_id:old.id,scores:Object.fromEntries((await rows('select * from competition_evaluation_scores where evaluation_id=$1',[old.id])).map(s=>[s.rubric_item_id,s.max_score]))});
 assert.equal(Number(await scalar('select quality_score from competition_evaluations where id=$1',[old.id])),100,'Evaluación histórica conservada');
