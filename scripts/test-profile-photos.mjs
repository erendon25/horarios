import assert from 'node:assert/strict';
import {createCompetitionTestDb} from './competition-test-db.mjs';
const db=await createCompetitionTestDb();
const scalar=async(sql,args=[])=>Object.values((await db.query(sql,args)).rows[0])[0];
const login=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated')};
const cmd=(id,action,payload={})=>scalar('select competition_command($1,$2,$3::jsonb)',[id,action,JSON.stringify(payload)]);
const photo=path=>scalar('select set_own_profile_photo($1)',[path]);
try {
  const store=await scalar('insert into stores default values returning id');
  const elsewhere=await scalar('insert into stores default values returning id');
  const users={},staff={};
  for(const role of ['admin','collaborator','rival','outsider']) {
    users[role]=await scalar('insert into auth.users values(gen_random_uuid()) returning id');
    staff[role]=await scalar("insert into staff_profiles(store_id,first_name,last_name,position) values($1,$2,'Prueba',$3) returning id",[role==='outsider'?elsewhere:store,role,role==='admin'?'ENTRENADOR':'COLABORADOR']);
    await db.query('insert into user_profiles(id,store_id,staff_profile_id,role) values($1,$2,$3,$4::app_role)',[users[role],role==='outsider'?elsewhere:store,staff[role],role==='admin'?'admin':'collaborator']);
  }
  await login(users.admin);
  const contest=await cmd(null,'create',{store_id:store});
  const team=await cmd(contest.id,'team',{name:'Equipo',trainer_staff_id:staff.admin});
  await cmd(contest.id,'member',{team_id:team.id,staff_id:staff.collaborator});
  await cmd(contest.id,'member',{team_id:team.id,staff_id:staff.rival});
  await login(users.collaborator);
  const first=`${users.collaborator}/profile.jpg`;
  const second=first;
  const foreign=`${users.rival}/profile.jpg`;
  const upload=path=>db.query("insert into storage.objects(bucket_id,name,owner_id) values('profile-photos',$1,$2)",[path,users.collaborator]);
  await assert.rejects(()=>upload(foreign),/row-level security/);
  await assert.rejects(()=>upload(`${users.collaborator}/unsafe.svg`),/row-level security/);
  await assert.rejects(()=>photo(first),/Primero sube/);
  await upload(first);
  await assert.rejects(()=>db.query('update storage.objects set name=$1 where name=$2',[foreign,first]),/row-level security/);
  await assert.rejects(()=>db.query('update storage.objects set owner_id=$1 where name=$2',[users.rival,first]),/row-level security/);
  const saved=await photo(first);
  assert.equal(saved.staff_id,staff.collaborator);assert.equal(saved.object_path,first);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),1);
  await assert.rejects(()=>db.query('update staff_profile_photos set staff_id=$1',[staff.rival]),/permission denied/);
  await assert.rejects(()=>db.query('delete from staff_profile_photos'),/permission denied/);
  await assert.rejects(()=>photo(foreign),/pertenecer a tu cuenta/);
  await login(users.rival);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),0,'Oculto: solo propietario y admin');
  assert.equal(Number(await scalar("select count(*) from storage.objects where name=$1",[first])),0);
  await login(users.admin);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),1);
  await cmd(contest.id,'publication',{published:true});
  await login(users.rival);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),1,'Participantes publicados pueden ver la foto');
  assert.equal(Number(await scalar('select count(*) from storage.objects where name=$1',[first])),1);
  assert.equal((await db.query('delete from storage.objects where name=$1 returning name',[first])).rows.length,0,'No puede eliminar la foto ajena');
  assert.equal((await db.query("update storage.objects set metadata='{}'::jsonb where name=$1 returning name",[first])).rows.length,0,'No puede sobrescribir la foto ajena');
  await login(users.outsider);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),0,'Otra tienda no ve fotos');
  assert.equal(Number(await scalar('select count(*) from storage.objects where name=$1',[first])),0);
  await login(users.admin);
  await cmd(contest.id,'publication',{published:false});
  await login(users.rival);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),0);
  assert.equal(Number(await scalar('select count(*) from storage.objects where name=$1',[first])),0);
  await login(users.collaborator);
  await db.query("update storage.objects set metadata='{}'::jsonb where name=$1",[second]);
  const replaced=await photo(second);assert.equal(replaced.previous_path,first);
  assert.equal(await scalar('select object_path from staff_profile_photos'),second);
  const removed=await photo(null);assert.equal(removed.previous_path,second);
  assert.equal(Number(await scalar('select count(*) from staff_profile_photos')),0);
  await photo(second);
  assert.equal((await db.query('delete from storage.objects where name=$1 returning name',[first])).rows.length,1);
  await db.exec('reset role');
  await db.query("update staff_profiles set cessation_date='2000-01-01' where id=$1",[staff.collaborator]);
  await login(users.collaborator);await assert.rejects(()=>photo(null),/Perfil no disponible/);
  await db.exec('reset role');
  await db.query("update staff_profiles set cessation_date=null where id=$1",[staff.collaborator]);
  await db.query("update user_profiles set status='inactive' where id=$1",[users.collaborator]);
  await login(users.collaborator);await assert.rejects(()=>photo(second),/vigente vinculado/);
  await db.exec('reset role');await db.exec('set role anon');
  await assert.rejects(()=>db.query('select * from staff_profile_photos'),/permission denied/);
  await assert.rejects(()=>photo(second),/permission denied/);
  await db.exec('reset role');
  const bucket=(await db.query("select * from storage.buckets where id='profile-photos'")).rows[0];
  assert.equal(bucket.public,false);assert.equal(Number(bucket.file_size_limit),2097152);
  assert.deepEqual(bucket.allowed_mime_types,['image/webp','image/jpeg','image/png']);
  console.log('PASS: foto propia, ruta y objeto verificados, RLS por publicación/tienda, denegación de escritura directa y cambios ajenos, reemplazo, eliminación, cuenta/perfil inactivo y bucket privado de 2 MB.');
} finally {await db.close()}
