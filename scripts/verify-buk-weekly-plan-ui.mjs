// Full editor with isolated HTTP persistence. No production data or Supabase calls.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const port=process.env.BUK_QA_PORT || '4186';
const base=`http://127.0.0.1:${port}`;
const output='output/buk-weekly-plan';
await mkdir(output,{recursive:true});
const fixture=JSON.parse(await readFile('artifacts/buk/fixture.json','utf8'));
const server=spawn(process.execPath,['scripts/serve-buk-qa.mjs'],{env:{...process.env,BUK_QA_PORT:port},stdio:['ignore','pipe','inherit']});
let browser,page;
const errors=[],passed=[];
const pass=name=>{passed.push(name);console.log(`PASS: ${name}`)};
try {
  await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(Error('QA server did not start in 30 seconds')),30000);
    server.once('error',error=>{clearTimeout(timeout);reject(error)});
    server.once('exit',code=>{clearTimeout(timeout);reject(Error(`QA server exited: ${code}`))});
    server.stdout.on('data',data=>{if(data.toString().includes('Editor BUK aislado:')){clearTimeout(timeout);resolve()}});
  });
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Lima'});
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  await page.goto(base);
  const day=page.locator('select').filter({has:page.locator('option[value="monday"]')});
  const rests=page.getByLabel('Descansos BUK de Prueba PT1',{exact:true});
  const approved=page.getByLabel('Horario aprobado BUK de Prueba PT1',{exact:true});
  const row=rests.locator('xpath=ancestor::tr[1]');
  await rests.waitFor();
  assert.equal(await rests.inputValue(),'1');
  await rests.selectOption('2');
  for(const key of ['monday','tuesday','wednesday','thursday','friday','saturday','sunday']) {
    await day.selectOption(key);
    assert.equal(await rests.inputValue(),'2',key);
    assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),fixture.schedules.PT1[key].start || '',key);
    assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),fixture.schedules.PT1[key].end || '',key);
  }
  pass('Plan de dos descansos uniforme en los siete días; turnos originales conservados');
  await day.selectOption('monday');
  assert.equal(await approved.locator('option[value="PT2-33"]').innerText(),'20:15 → 01:00 · 4 h 45 min');
  const ft=page.getByLabel('Horario aprobado BUK de Prueba FT1',{exact:true});
  assert.match(await ft.locator('option[value="FT1-5"]').innerText(),/8 h 45 min \(8 h netas\)/);
  await approved.selectOption('PT2-33');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),'20:15');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),'01:00');
  await day.selectOption('tuesday');
  await row.getByTitle('Entrada',{exact:true}).fill('20:15');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),'01:00');
  assert.equal(await approved.inputValue(),'PT2-33');
  pass('Duración de rangos nocturnos y horas netas; ingreso manual usa el mismo plan semanal');
  await page.reload();await rests.waitFor();
  assert.equal(await rests.inputValue(),'2');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),'20:15');
  pass('Borrador recupera la selección semanal tras recargar antes de guardar');
  await day.selectOption('saturday');
  const restColumn=await page.getByRole('columnheader',{name:'Libre',exact:true}).evaluate(element=>element.cellIndex);
  await row.locator('td').nth(restColumn).getByRole('checkbox').check();
  assert.equal(await rests.inputValue(),'2');
  await page.getByRole('button',{name:/^Guardar/}).click();
  await page.getByRole('button',{name:/^Guardado/}).waitFor();
  const saved=(await (await page.request.get(`${base}/qa-document?path=schedules%2FPT1_2026-10-12_to_2026-10-18`)).json()).data;
  assert.ok(saved);
  for(const key of ['monday','tuesday','wednesday','thursday','friday','saturday','sunday']) assert.equal(saved[key].bukRestDays,2,key);
  assert.equal(saved.saturday.off,true);assert.equal(saved.sunday.off,true);
  assert.equal(saved.monday.position,fixture.schedules.PT1.monday.position);
  assert.equal(saved.wednesday.start,fixture.schedules.PT1.wednesday.start);
  assert.equal(saved.wednesday.extraHoursPost,fixture.schedules.PT1.wednesday.extraHoursPost);
  assert.equal(await page.evaluate(()=>window.bukQaWrites.length),1,'Only edited collaborator is saved');
  assert.equal((await (await page.request.get(`${base}/qa-document?path=schedules%2FFT1_2026-10-12_to_2026-10-18`)).json()).found,false);
  await page.evaluate(()=>{for(const key of Object.keys(localStorage))if(key.startsWith('schedule_draft_v2:'))localStorage.removeItem(key)});
  await page.reload();await rests.waitFor();
  assert.equal(await rests.inputValue(),'2','Read weekly preference back from the saved document, without a local draft');
  await day.selectOption('sunday');assert.equal(await rests.inputValue(),'2');
  await day.selectOption('monday');assert.equal(await approved.inputValue(),'PT2-33');
  pass('Guardar y recargar conserva el plan completo y afecta solo al colaborador editado');
  await day.selectOption('saturday');
  await row.locator('td').nth(restColumn).getByRole('checkbox').uncheck();assert.equal(await rests.inputValue(),'1');
  await row.locator('td').nth(restColumn).getByRole('checkbox').check();assert.equal(await rests.inputValue(),'2');
  await day.selectOption('monday');
  pass('Marcar y desmarcar descansos reales actualiza el mismo plan para toda la semana');
  await row.screenshot({path:`output/buk-weekly-plan/fila-desktop.png`});
  await rests.selectOption('3');
  await day.selectOption('thursday');assert.equal(await rests.inputValue(),'3');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),fixture.schedules.PT1.thursday.start);
  await page.setViewportSize({width:390,height:844});
  await day.selectOption('monday');assert.equal(await rests.inputValue(),'3');
  await row.locator('td').nth(1).screenshot({path:`${output}/selector-mobile.png`});
  const mode=page.getByLabel('Modalidad de planificación',{exact:true});
  await mode.selectOption('legacy');await page.getByRole('button',{name:'Excel GeoVictoria',exact:true}).waitFor();
  await mode.selectOption('buk');await rests.waitFor();assert.equal(await rests.inputValue(),'3');
  pass('Cambio a tres descansos, navegación móvil y modo anterior conservan los turnos y el plan');
  assert.deepEqual(errors,[]);
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'PASS',passed,errors,scope:'Editor React real, borradores reales y transporte/identidades ficticias con persistencia HTTP aislada; sin escrituras de producción'},null,2));
} catch(error) {
  await page?.screenshot({path:`${output}/fallo.png`,fullPage:true}).catch(()=>{});
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'FAIL',passed,errors,error:String(error)},null,2));
  throw error;
} finally {await browser?.close();server.kill();}
