// Full editor with isolated HTTP persistence. No production data or Supabase calls.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import * as XLSX from 'xlsx';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const port=process.env.BUK_QA_PORT || '4186';
const base=`http://127.0.0.1:${port}`;
const output='output/buk-weekly-plan';
await mkdir(output,{recursive:true});
const fixture=JSON.parse(await readFile('artifacts/buk/fixture.json','utf8'));
const server=spawn(process.execPath,['scripts/serve-buk-qa.mjs'],{env:{...process.env,BUK_QA_PORT:port},stdio:['ignore','pipe','inherit']});
let browser,page;
const errors=[],passed=[];
const pass=name=>{passed.push(name);console.log(`PASS: ${name}`)};
try {
  await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(Error('QA server did not start in 30 seconds')),30000);
    server.once('error',error=>{clearTimeout(timeout);reject(error)});
    server.once('exit',code=>{clearTimeout(timeout);reject(Error(`QA server exited: ${code}`))});
    server.stdout.on('data',data=>{if(data.toString().includes('Editor BUK aislado:')){clearTimeout(timeout);resolve()}});
  });
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Lima'});
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
  page.on('dialog',dialog=>dialog.accept());
  await page.goto(base);
  const day=page.locator('select').filter({has:page.locator('option[value="monday"]')});
  const rests=page.locator('select[aria-label="Descansos BUK de Prueba PT1"]:enabled');
  const approved=page.getByLabel('Horario aprobado BUK de Prueba PT1',{exact:true});
  const row=rests.locator('xpath=ancestor::tr[1]');
  await rests.waitFor();
  assert.equal(await rests.inputValue(),'1');
  await rests.selectOption('2');
  for(const key of ['monday','tuesday','wednesday','thursday','friday','saturday','sunday']) {
    await day.selectOption(key);
    assert.equal(await rests.inputValue(),'2',key);
    assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),fixture.schedules.PT1[key].start || '',key);
    assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),fixture.schedules.PT1[key].end || '',key);
  }
  pass('Plan de dos descansos uniforme en los siete días; turnos originales conservados');
  await day.selectOption('monday');
  assert.equal(await approved.locator('option[value="PT2-33"]').innerText(),'20:15 → 01:00 · 4 h 45 min (sin break)');
  assert.ok((await approved.locator('option').evaluateAll(options=>options.filter(option=>option.value).map(option=>option.value))).every(value=>value.startsWith('PT2-')));
  const ft=page.getByLabel('Horario aprobado BUK de Prueba FT1',{exact:true});
  assert.match(await ft.locator('option[value="FT1-5"]').innerText(),/8 h 45 min \(8 h netas; break de 45 min\)/);
  await approved.selectOption('PT2-33');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),'20:15');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),'01:00');
  const breakButton=row.getByRole('button',{name:'Asignar break de Prueba PT1 BUK',exact:true});
  assert.equal(await breakButton.count(),0,'The workbook has no break in PT2');
  const thirdApproved=page.getByLabel('Horario aprobado BUK de Prueba PT3',{exact:true});
  const thirdRow=thirdApproved.locator('xpath=ancestor::tr[1]');
  const thirdBreak=thirdRow.getByRole('button',{name:'Asignar break de Prueba PT3 BUK',exact:true});
  assert.equal(await thirdApproved.locator('option[value="PT3-5"]').count(),0,'The short PT3 slot is already used on Thursday');
  await day.selectOption('thursday');
  assert.equal(await thirdBreak.count(),0,'PT3 short 5:45 has no break');
  await day.selectOption('monday');
  await thirdApproved.selectOption('PT3-62');
  await thirdBreak.click();
  await page.getByRole('combobox',{name:'Inicio del break',exact:true}).selectOption('23:00');
  await page.getByText('Descanso: 23:00–23:45',{exact:true}).waitFor();
  await page.getByRole('dialog',{name:'Break de Prueba PT3 BUK',exact:true}).screenshot({path:`${output}/break-segun-excel-modal.png`});
  await page.getByRole('button',{name:'Aplicar break',exact:true}).click();
  assert.equal(await thirdBreak.innerText(),'23:00');
  assert.equal(await thirdRow.locator('td').nth(6).innerText(),'6:00');
  const fourthRow=page.getByLabel('Horario aprobado BUK de Prueba PT4',{exact:true}).locator('xpath=ancestor::tr[1]');
  assert.equal(await fourthRow.getByRole('button',{name:'Asignar break de Prueba PT4 BUK',exact:true}).count(),1);
  assert.equal(await row.locator('td').nth(6).innerText(),'4:45');
  const pt2row=page.getByLabel('Horario aprobado BUK de Prueba PT2',{exact:true}).locator('xpath=ancestor::tr[1]');
  assert.match(await pt2row.locator('td').nth(7).innerText(),/23:45/);
  pass('PT2 sin break; PT3 con break solo en 6:45; PT4 con break; horas diarias y semanales según el Excel');
  await thirdRow.getByText('Refrigerio BUK: 23:00–23:45.',{exact:true}).waitFor();
  await thirdBreak.click();
  await page.getByRole('combobox',{name:'Inicio del break',exact:true}).selectOption('23:45');
  await page.getByRole('button',{name:'Aplicar break',exact:true}).click();
  const differentBukDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Excel BUK',exact:true}).click();
  await (await differentBukDownload).saveAs(`${output}/buk-refrigerios-distintos.xls`);
  await page.getByRole('status').filter({hasText:'1 break de cobertura difiere y se conserva'}).waitFor();
  const differentBuk=XLSX.read(await readFile(`${output}/buk-refrigerios-distintos.xls`),{type:'buffer'});
  const fixedCatalog=XLSX.utils.sheet_to_json(differentBuk.Sheets.turnosSemanales,{header:1});
  assert.deepEqual(fixedCatalog.find(r=>r[1]==='20:15 A 03:00'&&r[2]==='Lunes').slice(5),['23:00','23:45']);
  const comparisonDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Excel planificación',exact:true}).click();
  await (await comparisonDownload).saveAs(`${output}/planificacion-refrigerios-distintos.xls`);
  const comparison=XLSX.read(await readFile(`${output}/planificacion-refrigerios-distintos.xls`),{type:'buffer'});
  assert.ok(comparison.Sheets.BUK);assert.equal(comparison.Sheets['BUK PENDIENTE'],undefined);
  const comparisonRows=XLSX.utils.sheet_to_json(comparison.Sheets.REFRIGERIOS,{header:1});
  const differentBreak=comparisonRows.find(r=>r[0]==='Prueba PT3 BUK'&&r[2]==='2026-10-12');
  assert.deepEqual(differentBreak.slice(-3),['23:00–23:45','23:45–00:30','Diferencia de refrigerio']);
  assert.equal(await thirdBreak.innerText(),'23:45','Downloading the comparison does not move the chosen break');
  await thirdBreak.click();
  await page.getByRole('combobox',{name:'Inicio del break',exact:true}).selectOption('23:00');
  await page.getByRole('button',{name:'Aplicar break',exact:true}).click();
  pass('BUK exporta con su refrigerio fijo, conserva el break de cobertura y permite consultar ambas horas por persona/fecha');
  await day.selectOption('tuesday');
  await row.getByTitle('Entrada',{exact:true}).fill('20:15');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),'01:00');
  assert.equal(await approved.inputValue(),'PT2-33');
  pass('Duración de rangos nocturnos y horas netas; ingreso manual usa el mismo plan semanal');
  await page.reload();await rests.waitFor();
  assert.equal(await rests.inputValue(),'2');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),'20:15');
  pass('Borrador recupera la selección semanal tras recargar antes de guardar');
  await day.selectOption('saturday');
  const restColumn=await page.getByRole('columnheader',{name:'Libre',exact:true}).evaluate(element=>element.cellIndex);
  await row.locator('td').nth(restColumn).getByRole('checkbox').check();
  assert.equal(await rests.inputValue(),'2');
  assert.equal(await approved.isDisabled(),true,'Day off locks the approved-shift selector');
  assert.equal(await approved.locator('option:checked').innerText(),'Día libre');
  await approved.evaluate(select=>{select.value='PT2-33';select.dispatchEvent(new Event('change',{bubbles:true}))});
  assert.equal(await row.locator('td').nth(restColumn).getByRole('checkbox').isChecked(),true,'A stale selection cannot remove the rest day');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),'');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),'');
  pass('Día libre bloquea el selector y no puede desmarcarse asignando un turno');
  await page.getByRole('button',{name:/^Guardar/}).click();
  await page.getByRole('button',{name:/^Guardado/}).waitFor();
  const saved=(await (await page.request.get(`${base}/qa-document?path=schedules%2FPT1_2026-10-12_to_2026-10-18`)).json()).data;
  assert.ok(saved);
  for(const key of ['monday','tuesday','wednesday','thursday','friday','saturday','sunday']) assert.equal(saved[key].bukRestDays,2,key);
  assert.equal(saved.saturday.off,true);assert.equal(saved.sunday.off,true);
  assert.equal(saved.monday.breakStart,'');assert.equal(saved.monday.bukBreakIncludedInHours,false);
  const savedThird=(await (await page.request.get(`${base}/qa-document?path=schedules%2FPT3_2026-10-12_to_2026-10-18`)).json()).data;
  assert.equal(savedThird.monday.breakStart,'23:00');
  assert.equal(saved.monday.position,fixture.schedules.PT1.monday.position);
  assert.equal(saved.wednesday.start,fixture.schedules.PT1.wednesday.start);
  assert.equal(saved.wednesday.extraHoursPost,fixture.schedules.PT1.wednesday.extraHoursPost);
  assert.equal(await page.evaluate(()=>window.bukQaWrites.length),2,'Only the two edited collaborators are saved');
  assert.equal((await (await page.request.get(`${base}/qa-document?path=schedules%2FFT1_2026-10-12_to_2026-10-18`)).json()).found,false);
  await page.evaluate(()=>{for(const key of Object.keys(localStorage))if(key.startsWith('schedule_draft_v2:'))localStorage.removeItem(key)});
  await page.reload();await rests.waitFor();
  assert.equal(await rests.inputValue(),'2','Read weekly preference back from the saved document, without a local draft');
  await day.selectOption('sunday');assert.equal(await rests.inputValue(),'2');assert.equal(await approved.isDisabled(),true);
  await day.selectOption('monday');assert.equal(await approved.inputValue(),'PT2-33');
  assert.equal(await breakButton.count(),0,'PT2 remains without a break after reloading');
  assert.equal(await thirdBreak.innerText(),'23:00','PT3 required break survives saving and reloading');
  for(const [name,file] of [['Excel BUK','buk-reglas-excel.xls'],['Excel planificación','planificacion-reglas-excel.xls']]) {
    const pending=page.waitForEvent('download');await page.getByRole('button',{name,exact:true}).click();
    await (await pending).saveAs(`${output}/${file}`);
  }
  const buk=XLSX.read(await readFile(`${output}/buk-reglas-excel.xls`),{type:'buffer'});
  const bukRows=XLSX.utils.sheet_to_json(buk.Sheets.turnosColaboradores,{header:1,defval:''});
  assert.equal(bukRows.find(r=>r[1]===fixture.staff[1].dni)[4],'20:15 A 01:00');
  const planning=XLSX.read(await readFile(`${output}/planificacion-reglas-excel.xls`),{type:'buffer'});
  assert.equal(XLSX.utils.sheet_to_json(planning.Sheets['PLANIFICACIÓN'],{header:1}).find(r=>r[1]==='Prueba PT2 BUK').at(-2),'23:45');
  assert.equal(XLSX.utils.sheet_to_json(planning.Sheets['PLANIFICACIÓN'],{header:1}).find(r=>r[1]==='Prueba PT3 BUK').at(-2),'23:45');
  pass('Reglas de break persisten y ambos Excel se descargan con código BUK válido y 23:45 en PT2/PT3');
  pass('Guardar y recargar conserva el plan completo y afecta solo a los colaboradores editados');
  await day.selectOption('saturday');
  assert.equal(await approved.isDisabled(),true);
  await row.locator('td').nth(restColumn).getByRole('checkbox').uncheck();assert.equal(await rests.inputValue(),'1');
  assert.equal(await approved.isEnabled(),true,'Removing the rest day unlocks the selector');
  await row.locator('td').nth(restColumn).getByRole('checkbox').check();assert.equal(await rests.inputValue(),'2');
  assert.equal(await approved.isDisabled(),true);
  await day.selectOption('monday');
  pass('Marcar y desmarcar descansos reales actualiza el mismo plan para toda la semana');
  await row.screenshot({path:`output/buk-weekly-plan/fila-desktop.png`});
  await rests.selectOption('3');
  await day.selectOption('thursday');assert.equal(await rests.inputValue(),'3');
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),fixture.schedules.PT1.thursday.start);
  await page.setViewportSize({width:390,height:844});
  await day.selectOption('monday');assert.equal(await rests.inputValue(),'3');
  await row.locator('td').nth(1).screenshot({path:`${output}/selector-mobile.png`});
  const mode=page.getByLabel('Modalidad de planificación',{exact:true});
  await mode.selectOption('legacy');await page.getByRole('button',{name:'Excel GeoVictoria',exact:true}).waitFor();
  await mode.selectOption('buk');await rests.waitFor();assert.equal(await rests.inputValue(),'3');
  pass('Cambio a tres descansos, navegación móvil y modo anterior conservan los turnos y el plan');
  assert.deepEqual(errors,[]);
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'PASS',passed,errors,scope:'Editor React real, borradores reales y transporte/identidades ficticias con persistencia HTTP aislada; sin escrituras de producción'},null,2));
} catch(error) {
  await page?.screenshot({path:`${output}/fallo.png`,fullPage:true}).catch(()=>{});
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'FAIL',passed,errors,error:String(error)},null,2));
  throw error;
} finally {await browser?.close();server.kill();}
