// BUK is the only editor mode. Uses fictitious identities and isolated HTTP storage.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {isAbsolute} from 'node:path';
import {pathToFileURL} from 'node:url';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {scheduleDraftKey} from '../src/services/scheduleDraft.js';
const playwrightModule=process.env.PLAYWRIGHT_MODULE || 'playwright';
const {chromium}=await import(isAbsolute(playwrightModule)?pathToFileURL(playwrightModule).href:playwrightModule);
const port=process.env.BUK_QA_PORT || '4187';
const base=`http://127.0.0.1:${port}`;
const output='output/buk-only-mode';
await mkdir(output,{recursive:true});
const fixture=JSON.parse(await readFile('artifacts/buk/fixture.json','utf8'));
const scope={userId:'qa-admin',storeId:'qa-store',weekKey:'2026-10-12_to_2026-10-18'};
const draftKey=scheduleDraftKey(scope);
const preferenceKey='schedule_mode:qa-admin:qa-store';
const documentPath=`schedules/FT1_${scope.weekKey}`;
const historical=structuredClone(fixture.schedules.FT1);
historical.monday={start:fixture.schedules.FT1.monday.start,end:fixture.schedules.FT1.monday.end,
  splitShift:true,start2:'17:00',end2:'19:00',position:'LANDING',extraHoursPost:1};
const draftTuesday={...fixture.schedules.FT1.tuesday,position:'MASA',extraHoursPost:2};
const envelope={version:2,...scope,updatedAt:'2026-10-19T12:00:00.000Z',changes:{FT1:{tuesday:draftTuesday}}};
const server=spawn(process.execPath,['scripts/serve-buk-qa.mjs'],{env:{...process.env,BUK_QA_PORT:port},stdio:['ignore','pipe','inherit']});
let browser,page;
const errors=[],passed=[];
const pass=name=>{passed.push(name);console.log(`PASS: ${name}`)};
try {
  await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(Error('QA server did not start in 30 seconds')),30000);
    server.once('error',error=>{clearTimeout(timeout);reject(error)});
    server.once('exit',code=>{clearTimeout(timeout);reject(Error(`QA server exited: ${code}`))});
    server.stdout.on('data',data=>{if(data.toString().includes('Editor BUK aislado:')){clearTimeout(timeout);resolve()}});
  });
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Lima'});
  await context.addInitScript(({draftKey,preferenceKey,envelope})=>{
    if(localStorage.getItem('buk_qa_unique_mode_initialized'))return;
    localStorage.setItem(preferenceKey,'legacy');
    localStorage.setItem(draftKey,JSON.stringify(envelope));
    localStorage.setItem('buk_qa_unique_mode_initialized','1');
  },{draftKey,preferenceKey,envelope});
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
  page.on('dialog',dialog=>dialog.accept());
  const seed=await page.request.post(`${base}/qa-document`,{data:{path:documentPath,data:historical}});
  assert.equal(seed.ok(),true);
  await page.goto(base);
  const approved=page.getByLabel('Horario aprobado BUK de Prueba FT1',{exact:true});
  const row=approved.locator('xpath=ancestor::tr[1]');
  const day=page.locator('select').filter({has:page.locator('option[value="monday"]')});
  const storedDraft=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),draftKey);
  const storedSchedule=async()=>{const result=await (await page.request.get(`${base}/qa-document?path=${encodeURIComponent(documentPath)}`)).json();assert.equal(result.found,true);return result.data};
  const assertBukOnly=async()=>{
    await approved.waitFor();
    assert.equal(await page.getByLabel('Modalidad de planificación',{exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Excel GeoVictoria',exact:true}).count(),0);
    assert.equal(await page.getByRole('columnheader',{name:'Partido',exact:true}).count(),0);
    await page.getByRole('button',{name:'Excel BUK',exact:true}).waitFor();
    assert.equal(await page.evaluate(key=>localStorage.getItem(key),preferenceKey),'legacy','An obsolete preference is ignored without touching stored data');
  };
  await assertBukOnly();
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),historical.monday.start);
  assert.equal(await row.getByTitle('Entrada del segundo tramo',{exact:true}).inputValue(),'17:00');
  assert.equal(await row.getByTitle('Salida del segundo tramo',{exact:true}).inputValue(),'19:00');
  assert.equal(await approved.inputValue(),'','A split shift is not presented as an approved BUK range');
  await row.getByText('Turno partido conservado. Elige un horario BUK para reemplazar ambos tramos.',{exact:true}).waitFor();
  assert.deepEqual(await storedDraft(),envelope,'Loading BUK does not convert the old draft');
  assert.deepEqual(await storedSchedule(),historical,'Loading BUK does not rewrite historical schedules');
  assert.equal(await page.evaluate(()=>window.bukQaWrites.length),0);
  pass('BUK único ignora la preferencia legacy y conserva el turno histórico y el borrador sin escrituras');
  await day.selectOption('tuesday');
  assert.equal(await row.locator('input[type="number"]').nth(1).inputValue(),'2');
  await page.reload();await assertBukOnly();
  await day.selectOption('monday');
  await row.getByTitle('Entrada',{exact:true}).fill('06:45');
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),historical.monday.end,'A manual edit must not replace a historical split shift');
  const changes=(await storedDraft()).changes.FT1;
  assert.equal(changes.monday.splitShift,true);
  assert.equal(changes.monday.start2,'17:00');assert.equal(changes.monday.end2,'19:00');
  assert.deepEqual(changes.tuesday,draftTuesday,'Editing Monday preserves the recovered Tuesday draft');
  await page.getByRole('button',{name:/^Guardar/}).click();
  await page.getByRole('button',{name:/^Guardado/}).waitFor();
  let saved=await storedSchedule();
  assert.equal(saved.monday.start,'06:45');assert.equal(saved.monday.splitShift,true);
  assert.equal(saved.monday.start2,'17:00');assert.equal(saved.monday.end2,'19:00');
  assert.equal(saved.monday.extraHoursPost,1);assert.equal(saved.monday.position,'LANDING');
  assert.deepEqual(saved.tuesday,draftTuesday);assert.deepEqual(saved.wednesday,historical.wednesday);
  assert.equal(await page.evaluate(()=>window.bukQaWrites.length),1,'Only the edited collaborator is saved');
  assert.deepEqual((await storedDraft()).changes,{});
  pass('Editar, guardar y recargar conserva ambos tramos históricos, el borrador recuperado y los demás días');
  await page.reload();await assertBukOnly();
  assert.equal(await row.getByTitle('Entrada del segundo tramo',{exact:true}).inputValue(),'17:00');
  await approved.selectOption(fixture.schedules.FT1.monday.bukApprovedShiftId);
  assert.equal(await row.getByTitle('Entrada',{exact:true}).inputValue(),fixture.schedules.FT1.monday.start);
  assert.equal(await row.getByTitle('Salida',{exact:true}).inputValue(),fixture.schedules.FT1.monday.end);
  assert.equal(await row.getByTitle('Entrada del segundo tramo',{exact:true}).count(),0);
  assert.equal(await page.evaluate(()=>window.bukQaWrites.length),0,'Choosing BUK remains local until Save');
  await page.getByRole('button',{name:/^Guardar/}).click();
  await page.getByRole('button',{name:/^Guardado/}).waitFor();
  saved=await storedSchedule();
  assert.equal(saved.monday.splitShift,false);assert.equal(saved.monday.start2,'');assert.equal(saved.monday.end2,'');
  assert.equal(saved.monday.bukApprovedShiftId,fixture.schedules.FT1.monday.bukApprovedShiftId);
  assert.equal(saved.monday.extraHoursPost,1);assert.equal(saved.monday.position,'LANDING');
  assert.deepEqual(saved.tuesday,draftTuesday);assert.deepEqual(saved.wednesday,historical.wednesday);
  pass('Elegir explícitamente un horario BUK reemplaza ambos tramos sin perder extras, posición ni otros días');
  assert.deepEqual(errors,[]);
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'PASS',passed,errors,scope:'Editor React real con identidades ficticias y persistencia HTTP aislada; sin datos de producción'},null,2));
} catch(error) {
  await page?.screenshot({path:`${output}/fallo.png`,fullPage:true}).catch(()=>{});
  await writeFile(`${output}/resultado.json`,JSON.stringify({status:'FAIL',passed,errors,error:String(error)},null,2));
  throw error;
} finally {await browser?.close();server.kill();}
